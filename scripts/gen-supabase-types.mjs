/**
 * Windows-safe `supabase gen types typescript --local` → database.types.ts
 * Usage: pnpm supabase:types  (requires local stack up)
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outPath = path.join(root, "src/shared/api/database.types.ts");

const result = spawnSync(
  "npx",
  ["--yes", "supabase", "gen", "types", "typescript", "--local"],
  { cwd: root, encoding: "utf8", shell: process.platform === "win32" },
);

if (result.status !== 0) {
  console.error(result.stderr || result.stdout || "supabase gen types failed");
  console.error("Start Docker + `pnpm supabase:start` first, then retry.");
  process.exit(result.status ?? 1);
}

const header = `/**
 * AUTO-GENERATED by \`pnpm supabase:types\` from local Supabase.
 * Do not hand-edit — re-run after migration changes.
 */
`;

fs.writeFileSync(outPath, header + (result.stdout || ""), "utf8");
console.info(`[supabase:types] wrote ${path.relative(root, outPath)}`);
